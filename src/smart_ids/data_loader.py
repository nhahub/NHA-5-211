def standardize_labels(raw_label: str) -> Optional[str]:
    """Map raw CICIDS2017 label variants to the canonical 8-class taxonomy.

    Args:
        raw_label: Original raw string label from the CSV export.

    Returns:
        Standardized label matching one of the 8 classes, or None if excluded.
    """
    clean = str(raw_label).strip()
    upper = clean.upper()
    if "BENIGN" in upper:
        return "BENIGN"
    if "HULK" in upper:
        return "DoS Hulk"
    if "PORTSCAN" in upper:
        return "PortScan"
    if "DDOS" in upper:
        return "DDoS"
    if "GOLDENEYE" in upper:
        return "DoS GoldenEye"
    if "FTP-PATATOR" in upper:
        return "FTP-Patator"
    if "SSH-PATATOR" in upper:
        return "SSH-Patator"
    if "WEB ATTACK" in upper:
        return "Web Attack"
    return None


def generate_synthetic_cicids(
    n_samples: int = 200000,
    random_state: int = SEED,
    include_metadata: bool = True,
) -> pd.DataFrame:
    """Generate a realistic synthetic CICIDS2017 dataset.

    Faithfully reproduces the 76 continuous features, class distribution skew,
    zero-division infinity occurrences, occasional missing values, and duplicate rows.

    Args:
        n_samples: Target row count to synthesize (default 200,000).
        random_state: PRNG seed for reproducible generation.
        include_metadata: Whether to prepend structural columns (IP, Port, Timestamp).

    Returns:
        pd.DataFrame: Schema-compliant dataset ready for the pipeline.
    """
    rng = np.random.default_rng(random_state)
    logger.info("Synthesizing %d network flow records with seed %d...", n_samples, random_state)

    # Sample class labels according to realistic empirical weights
    labels_list = list(CLASS_WEIGHTS.keys())
    probs = np.array([CLASS_WEIGHTS[c] for c in labels_list], dtype=np.float64)
    probs /= probs.sum()

    assigned_labels = rng.choice(labels_list, size=n_samples, p=probs)

    # Base feature array drawn from standard lognormal/exponential distributions
    n_feat = len(CICFLOWMETER_FEATURES)
    data = rng.lognormal(mean=1.5, sigma=1.2, size=(n_samples, n_feat))

    # Apply class-distinct statistical signatures so models learn realistic boundaries
    for idx, label in enumerate(assigned_labels):
        if label == "DoS Hulk":
            # Very high packet rates and large byte volumes
            data[idx, 1] *= 15.0  # Total Fwd Packets
            data[idx, 13] *= 40.0  # Flow Bytes/s
            data[idx, 14] *= 25.0  # Flow Packets/s
        elif label == "PortScan":
            # Low duration, single packet, high SYN flags
            data[idx, 0] = rng.uniform(1.0, 50.0)  # Flow Duration
            data[idx, 43] = rng.choice([1.0, 2.0, 4.0])  # SYN Flag Count
            data[idx, 1] = rng.choice([1.0, 2.0])
        elif label == "DDoS":
            # Aggressive distributed packet flooding
            data[idx, 0] *= 0.5
            data[idx, 13] *= 30.0
            data[idx, 14] *= 50.0
            data[idx, 46] = 1.0  # ACK Flag Count
        elif label == "DoS GoldenEye":
            # Layer-7 slow-rate keep-alive exploitation
            data[idx, 0] *= 8.0
            data[idx, 14] *= 0.2
            data[idx, 15] *= 10.0  # Flow IAT Mean
        elif label == "FTP-Patator":
            # Repeated authentication attempts on port 21
            data[idx, 3] = rng.uniform(100.0, 500.0)  # Length Fwd
            data[idx, 45] = 1.0  # PSH Flag
        elif label == "SSH-Patator":
            # Encrypted handshake credential brute force on port 22
            data[idx, 3] = rng.uniform(200.0, 800.0)
            data[idx, 45] = 1.0
        elif label == "Web Attack":
            # Web injection payload characteristics
            data[idx, 3] = rng.uniform(1500.0, 5000.0)  # Large HTTP request
            data[idx, 45] = 1.0

    df_synth = pd.DataFrame(data, columns=CICFLOWMETER_FEATURES)

    # Inject zero-division infinity artifacts in rate columns (0.08% of rows)
    inf_indices = rng.choice(n_samples, size=max(10, int(n_samples * 0.0008)), replace=False)
    rate_cols = ["Flow Bytes/s", "Flow Packets/s"]
    for col in rate_cols:
        if col in df_synth.columns:
            df_synth.loc[inf_indices[: len(inf_indices) // 2], col] = np.inf
            df_synth.loc[inf_indices[len(inf_indices) // 2 :], col] = -np.inf

    # Inject a small fraction of missing values (<0.05% of rows)
    nan_indices = rng.choice(n_samples, size=max(10, int(n_samples * 0.0005)), replace=False)
    df_synth.loc[nan_indices, "Flow Bytes/s"] = np.nan

    df_synth["Label"] = assigned_labels

    if include_metadata:
        # Generate representative IP addresses and ports
        ip_octets = rng.integers(1, 254, size=(n_samples, 4))
        src_ips = [f"{o[0]}.{o[1]}.{o[2]}.{o[3]}" for o in ip_octets]

        dst_ports = []
        for label in assigned_labels:
            if label == "FTP-Patator":
                dst_ports.append(21)
            elif label == "SSH-Patator":
                dst_ports.append(22)
            elif label == "Web Attack":
                dst_ports.append(80)
            elif label in ("DoS Hulk", "DoS GoldenEye"):
                dst_ports.append(80)
            elif label == "PortScan":
                dst_ports.append(int(rng.choice([21, 22, 23, 25, 53, 80, 443, 8080])))
            else:
                dst_ports.append(int(rng.choice([80, 443, 53, 8080, 22])))

        df_synth.insert(0, "Source IP", src_ips)
        df_synth.insert(1, "Destination IP", "192.168.10.50")
        df_synth.insert(2, "Destination Port", dst_ports)
        df_synth.insert(
            3,
            "Timestamp",
            pd.date_range("2026-11-17 09:00:00", periods=n_samples, freq="100ms").astype(str),
        )

    # Inject duplicate rows (~0.1% duplicates) to test deduplication
    n_dupes = max(5, int(n_samples * 0.001))
    dupe_rows = df_synth.iloc[:n_dupes].copy()
    df_synth = pd.concat([df_synth, dupe_rows], ignore_index=True)

    logger.info("Synthetic dataset created: %d rows, %d columns", len(df_synth), df_synth.shape[1])
    return df_synth


def load_cicids2017(
    data_dir: Union[str, Path] = RAW_DATA_DIR,
    sample_size: Optional[int] = 200000,
    random_state: int = SEED,
) -> pd.DataFrame:
    """Load and merge raw CICIDS2017 CSV files from disk.

    Strips column names of whitespace, filters for the canonical 8 attack classes,
    and returns a sampled unified dataframe. If no CSV files are found, falls back
    to generating a synthetic dataset.

    Args:
        data_dir: Path to directory containing raw CSV files.
        sample_size: Desired sample size (~200,000). None loads all available rows.
        random_state: Random state for downsampling.

    Returns:
        pd.DataFrame: Merged or synthetic dataset.
    """
    path = Path(data_dir)
    csv_files = sorted(list(path.glob("*.csv")))

    if not csv_files:
        logger.warning(
            "No CSV files found in '%s'. Falling back to synthetic CICIDS2017 generator.",
            path.resolve(),
        )
        return generate_synthetic_cicids(
            n_samples=sample_size or 200000,
            random_state=random_state,
            include_metadata=True,
        )

    logger.info("Found %d CSV files in '%s'. Loading...", len(csv_files), path)
    dfs: List[pd.DataFrame] = []

    for f in csv_files:
        try:
            logger.info("Reading %s...", f.name)
            df_part = pd.read_csv(f, low_memory=False)
            df_part.columns = df_part.columns.str.strip()

            # Identify label column
            label_col = next((c for c in df_part.columns if c.lower() == "label"), None)
            if label_col:
                df_part["Label"] = df_part[label_col].apply(standardize_labels)
                df_part = df_part.dropna(subset=["Label"])
            dfs.append(df_part)
        except Exception as e:
            logger.error("Error reading file %s: %s", f.name, e)

    if not dfs:
        logger.warning("All CSV reads failed or produced no rows. Using synthetic fallback.")
        return generate_synthetic_cicids(
            n_samples=sample_size or 200000,
            random_state=random_state,
            include_metadata=True,
        )

    merged = pd.concat(dfs, ignore_index=True)
    logger.info("Merged %d raw rows across %d files.", len(merged), len(dfs))

    if sample_size and len(merged) > sample_size:
        logger.info("Stratified downsampling to %d rows...", sample_size)
        # Stratified sampling by Label
        merged = (
            merged.groupby("Label", group_keys=False)
            .apply(lambda g: g.sample(frac=sample_size / len(merged), random_state=random_state))
            .reset_index(drop=True)
        )

    return merged
